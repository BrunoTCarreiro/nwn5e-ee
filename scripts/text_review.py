"""docs/TEXT-REVIEW.md (#168): the player text that is nwn5e's wording, for the owner's review - from data/text/en.txt,
data/strings.txt + data/text/strings_sources.txt and tests/data/fixtures/text_literals.txt.

Usage (from the repo): python -I scripts/text_review.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def cell(text):
    return text.replace("\\n", "<br>").replace("\n", "<br>").replace("|", "\\|")


catalog = []
for line in (ROOT / "data/text/en.txt").read_text(encoding="utf-8").splitlines():
    if not line.strip() or line.lstrip().startswith("#"):
        continue
    key, source, text = line.split(" | ", 2)
    catalog.append((key.strip(), source.strip(), text))
strings = {}
for line in (ROOT / "data/strings.txt").read_text(encoding="utf-8").splitlines():
    m = re.match(r"(\d{8}) (.*)$", line)
    if m:
        strings[m.group(1)] = m.group(2)
sources = {}
for line in (ROOT / "data/text/strings_sources.txt").read_text(encoding="utf-8").splitlines():
    if line and not line.startswith("#"):
        sources[line[:8]] = line[9:]
literals = []
for line in (ROOT / "tests/data/fixtures/text_literals.txt").read_text(encoding="utf-8").splitlines():
    if line and not line.startswith("#"):
        fields = line.split()  # <file> <TellPlayer> <Tell helper> <SendMessageToPC> [<"nwn5e: " literals>]
        name, tells, helpers, sends = fields[:4]
        chat_lines = int(fields[4]) if len(fields) > 4 else 0
        literals.append((name, int(tells) + int(helpers) + chat_lines, int(sends)))


def kind(source):
    if source.endswith("+note"):
        return "srd+note"
    return source.split(":")[0]


cat_counts, str_counts = {}, {}
for _, source, _ in catalog:
    cat_counts[kind(source)] = cat_counts.get(kind(source), 0) + 1
for sid in strings:
    k = kind(sources.get(sid, "?"))
    str_counts[k] = str_counts.get(k, 0) + 1

out = ["# Player text for review (#168)", "",
       "The owner's rule (2026-11-16): \"any new text is either written by me, or copied verbatim from the SRD. If you",
       "have to generate new text we'll need a document to keep track of it, maybe in an i18n style\". This page lists",
       "the player text that is nwn5e's own wording. It is generated by `scripts/text_review.py`, so don't edit it by hand.", "",
       "**Making a line yours:**",
       "- For a catalogue entry, rewrite its text in `data/text/en.txt` as you like and set its source to `owner`.",
       "- For a name or description, rewrite it in `data/strings.txt` and set its line in `data/text/strings_sources.txt`",
       "  to `owner`. For an `srd:...+note` description, only the part from \"nwn5e:\" on is generated.", "",
       "## Summary", "",
       "| Where | Owner | SRD 5.2.1 verbatim | SRD + generated note | Generated | Symbols |",
       "|---|---|---|---|---|---|",
       "| `data/text/en.txt` (messages) | %d | %d | %d | %d | %d |" % (
           cat_counts.get("owner", 0), cat_counts.get("srd", 0), cat_counts.get("srd+note", 0),
           cat_counts.get("generated", 0), cat_counts.get("symbol", 0)),
       "| `data/strings.txt` (names, descriptions) | %d | %d | %d | %d | %d |" % (
           str_counts.get("owner", 0), str_counts.get("srd", 0), str_counts.get("srd+note", 0),
           str_counts.get("generated", 0), str_counts.get("symbol", 0)), "",
       "**Still in the code, not yet in the catalogue:** %d chat messages and %d script messages in %d files (moved "
       "file by file)." % (sum(t for _, t, _ in literals), sum(s for _, _, s in literals), len(literals)), "",
       "## Catalogue entries (generated)", "", "| Key | Text |", "|---|---|"]
out += ["| `%s` | %s |" % (key, cell(text)) for key, source, text in catalog if source == "generated"]
out += ["", "## Names and descriptions (generated)", "", "| Id | Text |", "|---|---|"]
out += ["| %s | %s |" % (sid, cell(text)) for sid, text in strings.items() if sources.get(sid) == "generated"]
out += ["", "## The generated notes after SRD text", "", "| Id | SRD entry | Note |", "|---|---|---|"]
for sid, text in strings.items():
    source = sources.get(sid, "")
    if source.endswith("+note"):
        note = text[text.find("\\n\\nnwn5e:") + 4:] if "\\n\\nnwn5e:" in text else ""
        out.append("| %s | %s | %s |" % (sid, cell(source[4:-5]), cell(note)))
out += ["", "## Still in the code", "", "| File | Chat messages | Script messages |", "|---|---|---|"]
out += ["| `src/core/%s` | %d | %d |" % row for row in literals]
(ROOT / "docs/TEXT-REVIEW.md").write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print("docs/TEXT-REVIEW.md:", sum(1 for _, s, _ in catalog if s == "generated"), "catalogue,",
      str_counts.get("generated", 0), "strings,", str_counts.get("srd+note", 0), "notes generated")

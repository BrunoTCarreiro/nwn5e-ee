"""Writes data/rows/encumbrance.if_carry2024.txt: the 2024 carrying capacity as NWN's encumbrance table.

SRD 5.2 (Rules Glossary, "Carrying Capacity"): a Small or Medium creature carries up to
Strength x 15 lb. and drags, lifts or pushes up to Strength x 30 lb.; while moving more than it
can carry, its Speed is at most 5 feet. There is no lighter "encumbered" step.

NWN's encumbrance.2da (rows: Strength 0-100; tenths of a pound): over Normal the creature is
heavily encumbered (walks, can't run), over Heavy overloaded (walks, slowed). Both columns are
Strength x 150 here (x 15 lb), so anything over the capacity is overloaded - and
ruleset.if_carry2024.txt sets the overload to 4 movement stages: Speed x 0.125 (the engine's cap),
about 4 ft of 30. Served only with `carrying` faithful (src/core/rules_equipment.cpp).

usage: python tools/data/carrying_capacity.py
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "data", "rows", "encumbrance.if_carry2024.txt")
LB_PER_STRENGTH = 15  # Small / Medium (SRD 5.2)
TENTHS = 10           # encumbrance.2da counts tenths of a pound

lines = [
    "# encumbrance.2da - the 2024 carrying capacity (generated by tools/data/carrying_capacity.py;",
    "# `carrying` faithful, src/core/rules_equipment.cpp): Strength x 15 lb. carried with no penalty,",
    "# anything more overloaded (ruleset.if_carry2024.txt: Speed about 5 ft).",
    "Normal Heavy",
]
for strength in range(0, 101):
    tenths = strength * LB_PER_STRENGTH * TENTHS
    lines.append(f"{strength} {tenths} {tenths}")
with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(OUT)}: {len(lines) - 4} rows")

"""Writes C7a's data (docs/CHARGEN.md): Ability Score Improvement as feats with
their choices, and the feats a feat level offers besides it.

- data/rows/feat.asi2024.txt: the k-th ASI's 21 choices (k 1..7), feat rows
  1400 + 21 (k - 1) + split (rules::AsiSplitFeat): splits 0-5 = +2 to
  Strength .. Charisma, 6-20 = +1 to two (Str+Dex, Str+Con, ... Wis+Cha;
  rules::AsiSplit). Each under its ASI's master feat; nwn5e's feat filter
  offers only the next ASI's choices (rules_feats.cpp).
- data/rows/masterfeats.asi.txt: the seven masters (rows 45-51).
- data/rows/feat.skilled.txt: Skilled again (Repeatable, SRD 5.2): rows
  1302-1307, each needing the one before.
- data/rows/cls_feat_<class>.if_feats2024.txt: in the base classes' feat
  lists, only with feats faithful: the ASI choices (List 2: the 2024 feat
  slots, the class's bonus picks) and the Origin feats (Alert, Savage
  Attacker, Skilled), which 2024 allows at an ASI level ("another feat for
  which you qualify") - List 1, a bonus or a general pick: a Human's
  Versatile Origin feat at level 1 is the game's general (normal) pick, and
  CNWClass::IsNormalFeat answers from a class's list when the feat is in it
  (List 2 there kept them out of it; C8, 0.17.1).
- data/strings.txt 16000410-16000432: the choices' names, their description,
  the masters' name.

tests/data/asi_feats_test.cpp checks the rows against the rules.
Run from the repo root:  python tools/data/asi_feats.py
"""

import os

ABILITIES = ['Strength', 'Dexterity', 'Constitution', 'Intelligence', 'Wisdom', 'Charisma']
SHORT = ['STR', 'DEX', 'CON', 'INT', 'WIS', 'CHA']
ICONS = ['ife_X2GrStr1', 'ife_X2GrDex1', 'ife_X2GrCon1', 'ife_X2GrInt1', 'ife_X2GrWis1', 'ife_X2GrCha1']
SLOTS = 7
FIRST = 1400
MASTER_FIRST = 45
NAME_FIRST = 16000410      # 21 choice names
DESCRIPTION = 16000431     # the choices' and masters' description
MASTER_NAME = 16000432
SKILLED_AGAIN_FIRST, SKILLED_REPEATS = 1302, 6
CLASSES = ['barb', 'bard', 'cler', 'druid', 'fight', 'monk', 'pal', 'rang', 'rog', 'sorc', 'wiz']
ORIGIN = [('ImpInit', 377), ('NWN5E_SAVAGE_ATTACKER', 1300), ('NWN5E_SKILLED', 1301)]


def splits():
    """(first, second or None) for splits 0..20 — rules::AsiSplit's order."""
    out = [(a, None) for a in range(6)]
    out += [(a, b) for a in range(6) for b in range(a + 1, 6)]
    return out


def split_name(first, second):
    if second is None:
        return f'+2 {ABILITIES[first]}'
    return f'+1 {ABILITIES[first]}, +1 {ABILITIES[second]}'


def split_label(first, second):
    return SHORT[first] if second is None else f'{SHORT[first]}_{SHORT[second]}'


def write(path, lines):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    rows = os.path.join('data', 'rows')
    feat = [
        '# feat.2da - C7a (docs/CHARGEN.md): the k-th Ability Score Improvement\'s 21 choices,',
        '# row 1400 + 21 (k - 1) + split (rules::AsiSplitFeat); generated by tools/data/asi_feats.py.',
        '# Bonus-list feats (ALLCLASSESCANUSE 0); Level 4+ (the SRD feat\'s prerequisite).',
        'LABEL FEAT DESCRIPTION ICON GAINMULTIPLE EFFECTSSTACK ALLCLASSESCANUSE CRValue MASTERFEAT Constant '
        'TOOLSCATEGORIES PreReqEpic ReqAction MinLevel',
    ]
    class_rows = []
    for slot in range(1, SLOTS + 1):
        for split, (first, second) in enumerate(splits()):
            row = FIRST + 21 * (slot - 1) + split
            label = f'NWN5E_ASI_{slot}_{split_label(first, second)}'
            feat.append(f'{row} {label} {NAME_FIRST + split} {DESCRIPTION} {ICONS[first]} 0 0 0 1 '
                        f'{MASTER_FIRST + slot - 1} FEAT_{label} 6 0 1 4')
            class_rows.append(f'+ {label} {row} 2 -1 0')
    write(os.path.join(rows, 'feat.asi2024.txt'), feat)
    write(os.path.join(rows, 'masterfeats.asi.txt'), [
        '# masterfeats.2da - C7a: each Ability Score Improvement, the master of its 21 choices',
        '# (feat.asi2024.txt; generated by tools/data/asi_feats.py).',
        'LABEL STRREF DESCRIPTION ICON',
    ] + [f'{MASTER_FIRST + slot - 1} NWN5E_ASI_{slot} {MASTER_NAME} {DESCRIPTION} ife_X2GrStr1'
         for slot in range(1, SLOTS + 1)])
    write(os.path.join(rows, 'feat.skilled.txt'), [
        '# feat.2da - C7a: Skilled again (Repeatable, SRD 5.2), each needing the one before;',
        '# taken at feat levels (bonus lists, Level 4+). Generated by tools/data/asi_feats.py.',
        'LABEL FEAT DESCRIPTION ICON PREREQFEAT1 GAINMULTIPLE EFFECTSSTACK ALLCLASSESCANUSE CRValue Constant '
        'TOOLSCATEGORIES PreReqEpic ReqAction MinLevel',
    ] + [f'{SKILLED_AGAIN_FIRST + i} NWN5E_SKILLED_{i + 2} 16000392 16000393 ife_skfoc '
         f'{1301 if i == 0 else SKILLED_AGAIN_FIRST + i - 1} 0 0 0 1 FEAT_NWN5E_SKILLED_{i + 2} 6 0 1 4'
         for i in range(SKILLED_REPEATS)])
    origin_rows = [f'+ {label} {row} 1 -1 0' for label, row in ORIGIN]
    origin_rows += [f'+ NWN5E_SKILLED_{i + 2} {SKILLED_AGAIN_FIRST + i} 1 -1 0' for i in range(SKILLED_REPEATS)]
    for c in CLASSES:
        write(os.path.join(rows, f'cls_feat_{c}.if_feats2024.txt'), [
            f'# cls_feat_{c}.2da - C7a: the 2024 feat slots\' choices — the ASI\'s (feat.asi2024.txt) and',
            '# the Origin feats (List 1: a bonus or a general pick) - with feats faithful (generated by',
            '# tools/data/asi_feats.py).',
            'FeatLabel FeatIndex List GrantedOnLevel OnMenu',
        ] + class_rows + origin_rows)

    # Strings, between their markers in data/strings.txt.
    strings = os.path.join('data', 'strings.txt')
    text = open(strings, encoding='utf-8', newline='').read()
    nl = '\r\n' if '\r\n' in text else '\n'
    begin, end = '# BEGIN C7a ASI choices (tools/data/asi_feats.py)', '# END C7a ASI choices'
    block = [begin]
    block += [f'{NAME_FIRST + split} {split_name(first, second)}' for split, (first, second) in enumerate(splits())]
    block.append(f'{DESCRIPTION} Ability Score Improvement (2024): increase one ability score by 2, or two ability '
                 'scores by 1 each - choose it from this list; a score can\'t go above 20 (what doesn\'t fit is lost).'
                 '\\n\\nYou take one at each feat level of your class (4, 8, 12, 16, 19; Fighter 6, 14; Rogue 10), '
                 'or another feat you qualify for (an Origin feat, a Fighter\'s Fighting Style). Older characters\' '
                 'Ability Score Improvements are still chosen with !asi; !asi change swaps your last one.')
    block.append(f'{MASTER_NAME} Ability Score Improvement')
    block.append(end)
    if begin in text:
        head, rest = text.split(begin, 1)
        tail = rest.split(end, 1)[1]
        text = head + nl.join(block) + tail
    else:
        if not text.endswith(nl):
            text += nl
        text += nl.join(block) + nl
    open(strings, 'w', encoding='utf-8', newline='').write(text)
    print(f'{SLOTS * 21} ASI choices, {SLOTS} masters, {SKILLED_REPEATS} Skilled rows, {len(CLASSES)} class lists')


if __name__ == '__main__':
    main()

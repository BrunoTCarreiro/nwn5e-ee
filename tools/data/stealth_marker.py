"""The stealth marker: who has noticed a hiding player character.

Owner, 2026-10-25: "how possible is it to show enemys' sight ranges?" - then
"build your recommendation": an eye over each hostile creature that sees the
hiding character, an ear over one that only hears it (stealth_watch.cpp).

The icons are the game's own Spot and Listen skill icons (skills.2da: isk_spot,
isk_listen), used by name: the engine loads them from the player's install, so
nothing of the game's goes in the repo (as the death-save marker's icon).

  python tools/data/stealth_marker.py
      models in data/files, rows in data/rows/visualeffects.stealth.txt.

The models: ASCII effect models with one camera-facing particle (update Single,
render Normal - like death_save_marker.py's) that lives as long as the effect,
over the creature's head-conjure node, growing in and shrinking out. Rows:
visualeffects 1571 (seen) and 1572 (heard), duration effects on the head node.

Run from the repo root.
"""

import os

FILES = os.path.join("data", "files")
ROWS = os.path.join("data", "rows", "visualeffects.stealth.txt")
MARKERS = [
    # (model, visualeffects row, label, the game's icon by name)
    ("n5_seen", 1571, "NWN5E_STEALTH_SEEN", "isk_spot"),
    ("n5_heard", 1572, "NWN5E_STEALTH_HEARD", "isk_listen"),
]
SIZE_M = 0.45    # the icon's width in metres
HEIGHT_M = 0.45  # over the head-conjure node (just over the head)


def size_keys(points):
    lines = []
    for key in ("sizeStartkey", "sizeEndkey"):
        lines.append("  %s %d" % (key, len(points)))
        lines += ["    %g %g" % p for p in points]
    return lines


def emitter(node, parent, texture_name):
    return [
        "node emitter " + node,
        "  parent " + parent,
        "  p2p 0", "  p2p_sel 1", "  affectedByWind 0", "  m_isTinted 0", "  bounce 0", "  random 0",
        "  inherit 1", "  inheritvel 0", "  inherit_local 0", "  splat 0", "  inherit_part 0",
        "  renderorder 0", "  spawntype 0",
        "  update Single",
        "  render Normal",
        "  blend Normal",
        "  texture " + texture_name,
        "  xgrid 1", "  ygrid 1", "  loop 0", "  deadspace 0", "  twosidedtex 0",
        "  blastRadius 0", "  blastLength 0",
        "  position 0 0 %g" % HEIGHT_M,
        "  orientation 0 0 0 0",
        "  colorStart 1 1 1", "  colorEnd 1 1 1", "  alphaStart 1", "  alphaEnd 1",
        "  sizeStart 0", "  sizeEnd 0", "  sizeStart_y 0", "  sizeEnd_y 0",
        "  frameStart 0", "  frameEnd 0",
        "  birthrate 1",
        "  lifeExp -1",
        "  mass 0", "  spread 0", "  particleRot 0", "  velocity 0", "  randvel 0", "  fps 0",
        "  xsize 0", "  ysize 0", "  bounce_co 0", "  blurlength 10",
        "  lightningDelay 0", "  lightningRadius 0", "  lightningScale 0",
        "  p2p_bezier2 0", "  p2p_bezier3 0", "  combinetime 0", "  drag 0", "  grav 0", "  threshold 0",
        "endnode",
    ]


def write_model(name, icon):
    node = name + "_icon"
    lines = [
        "#MAXMODEL ASCII",
        "# nwn5e (tools/data/stealth_marker.py): the stealth marker - a camera-facing",
        "# sprite over a creature that has noticed a hiding player character: the",
        "# game's own %s icon (by name, from the player's install)." % icon,
        "newmodel " + name,
        "setsupermodel %s NULL" % name,
        "classification effect",
        "setanimationscale 1",
        "beginmodelgeom " + name,
        "node dummy " + name,
        "  parent NULL",
        "endnode",
    ]
    lines += emitter(node, name, icon)
    lines.append("endmodelgeom " + name)
    for anim, length, keys in (("impact", 0.25, [(0, 0), (0.15, 1.15), (0.25, 1)]),
                               ("duration", 1.0, [(0, 1), (1.0, 1)]),
                               ("cessation", 0.2, [(0, 1), (0.2, 0)])):
        lines += [
            "",
            "newanim %s %s" % (anim, name),
            "  length %g" % length,
            "  transtime 0.25",
            "  animroot " + name,
            "node dummy " + name,
            "  parent NULL",
            "endnode",
            "node emitter " + node,
            "  parent " + name,
        ]
        lines += size_keys([(t, SIZE_M * k) for t, k in keys])
        lines += ["endnode", "doneanim %s %s" % (anim, name)]
    lines += ["", "donemodel " + name, ""]
    with open(os.path.join(FILES, name + ".mdl"), "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    rows = [
        "# visualeffects.2da - the stealth marker (stealth_watch.cpp), generated by",
        "# tools/data/stealth_marker.py: an eye (seen) or an ear (heard) over a creature",
        "# that has noticed a hiding player character - nwn5e's models (data\\files\\n5_seen,",
        "# n5_heard) with the game's isk_spot / isk_listen icons by name, on the head node.",
        "Label Type_FD OrientWithGround Imp_HeadCon_Node OrientWithObject",
    ]
    for name, row, label, icon in MARKERS:
        write_model(name, icon)
        rows.append("%d %s D 0 %s 0" % (row, label, name))
    with open(ROWS, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(rows) + "\n")
    print("wrote %d marker models to %s, and %s" % (len(MARKERS), FILES, ROWS))


if __name__ == "__main__":
    main()
